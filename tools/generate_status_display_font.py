from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


FONT_PATH = Path(r"C:\Windows\Fonts\Noto Sans SC (TrueType).otf")
OUTPUT_PATH = Path(__file__).resolve().parents[1] / "include" / "status_display_font.h"

# Keep this list in sync with user-visible strings in src/display/status_display.cpp.
UI_TEXT = (
    "语音链路遥控器音频帧在线离线断开扫描连接中通话待机未就绪传输等待主机"
    "正常异常已启用麦克风电量缓冲样本运行状态错误最近秒丢版知"
)


def codepoints() -> list[int]:
    points = {ord(ch) for ch in UI_TEXT if not ch.isspace()}
    points.update(range(0x20, 0x7F))
    return sorted(points)


def pack_4bpp(image: Image.Image) -> list[int]:
    pixels = list(image.getdata())
    packed: list[int] = []
    for index in range(0, len(pixels), 2):
        high = min(15, pixels[index] // 17)
        low = min(15, pixels[index + 1] // 17) if index + 1 < len(pixels) else 0
        packed.append((high << 4) | low)
    return packed


def emit_font(
    lines: list[str], name: str, struct_name: str, size: int, cell: int
) -> None:
    font = ImageFont.truetype(str(FONT_PATH), size=size)
    points = codepoints()

    lines.extend(
        [
            f"static const {struct_name} {name}[] = {{",
        ]
    )

    for point in points:
        char = chr(point)
        image = Image.new("L", (cell, cell), 0)
        draw = ImageDraw.Draw(image)
        if point != 0x20:
            draw.text((0, 0), char, font=font, fill=255, anchor="lt")
        packed = pack_4bpp(image)
        advance = max(1, min(255, round(font.getlength(char))))
        data = ", ".join(f"0x{value:02X}" for value in packed)
        lines.append(
            "    {"
            f"0x{point:04X}, {advance}, {{{data}}}"
            "},"
        )

    lines.append("};")
    lines.append("")


def main() -> None:
    lines = [
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "#define STATUS_FONT_12_CELL 18",
        "#define STATUS_FONT_12_BYTES ((STATUS_FONT_12_CELL * STATUS_FONT_12_CELL + 1) / 2)",
        "#define STATUS_FONT_16_CELL 24",
        "#define STATUS_FONT_16_BYTES ((STATUS_FONT_16_CELL * STATUS_FONT_16_CELL + 1) / 2)",
        "",
        "struct StatusGlyph12 {",
        "    uint32_t codepoint;",
        "    uint8_t advance;",
        "    uint8_t alpha[STATUS_FONT_12_BYTES];",
        "};",
        "",
        "struct StatusGlyph16 {",
        "    uint32_t codepoint;",
        "    uint8_t advance;",
        "    uint8_t alpha[STATUS_FONT_16_BYTES];",
        "};",
        "",
        "// Generated by tools/generate_status_display_font.py.",
    ]

    emit_font(lines, "status_font_12", "StatusGlyph12", 12, 18)
    emit_font(lines, "status_font_16", "StatusGlyph16", 16, 24)

    OUTPUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"generated {OUTPUT_PATH} ({OUTPUT_PATH.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
